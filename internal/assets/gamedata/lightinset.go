package gamedata

// 戰場視野內縮量（能見度）。
//
// 進戰鬥時，戰場地形是「世界地圖上以遭遇位置為中心的一個視窗」貼進 9×9
// 網格裡。視窗不一定是滿的 9×9：它是 (9−2k)×(9−2k)，貼在網格的 (k,k)，
// 外圈維持空白。k 就是這裡說的內縮量 —— 看得越遠 k 越小。
//
// # k 從哪來
//
// 兩條路（`DEMON.INT`）：
//
//   - **戶外**（隊伍欄位 `+0xa3` ≥ 10，即身處編號 ≥ 10 的世界子地圖）：
//     k 查一張以「時辰」為索引的表（`DS:0x209c`，見 lightInsetByHour）。
//     時辰存在隊伍欄位 `+0x9f`。程式在 0x166b4：
//
//     166b4  mov al,es:[bx+0x9f]   ; 時辰
//     166bd  mov al,[bx+0x209c]    ; 查表
//     166c3  mov ds:0x4c86,ax      ; → k
//
//   - **其他情況**（地城等）：k = 4 − `ds:0x5c64`（0x161c5），
//     `0x5c64` 看起來是光源強度計數。這一條還沒完整追，本套件先不實作。
//
// 貼進網格的起始索引由 `DS:0x2208` 的表給，值就是 k*10 = 網格 (k,k) 的
// 索引（9 寬網格：k*9+k）。表只有 k=0..5 六筆有效，第 7 筆起是別的資料。
// 這也是戰場寬度為 9 的第三個獨立佐證（另兩個見 sight.go）。
const (
	// MaxLightInset 是內縮量的上限。k=4 時視窗只剩 1×1；
	// 起始索引表雖然有到 k=5，但 (9−2·5) 是負的，不可能用到。
	MaxLightInset = 4
)

// lightInsetByHour 是戶外的「時辰 → 內縮量」表，取自 DEMON.INT 的
// `DS:0x209c`（檔位移 0x27b9c）。
//
// 這是一條標準的日夜能見度曲線：正午前後看得最遠（k=0，整個 9×9 都畫），
// 黃昏與清晨各縮一圈，深夜只剩中央 3×3。
//
// **長度取 38** 對齊 `docs/spec/06-time.md` 的小時 wrap 常數 `0x26`。
// 原始資料在索引 18 之後一路是 3，直到第 41 筆才變成明顯的別種資料
// （37、51、100），所以光看內容分不出這張表到底是 38 筆還是 41 筆 ——
// 平的尾巴兩種切法都成立。這裡取 38 是因為它跟時間系統對得上；
// 真正的長度要等小時 wrap 被獨立確認後才算釘死。
//
// 附帶一提：手冊寫「一天 26 小時」，但這張表在索引 26 之後還有內容，
// 與 `06-time.md` 已記錄的「wrap 是 38 不是 26」一致，不支持手冊那個數字。
var lightInsetByHour = [38]byte{
	2, 2, 2, 1, 1, 0, 0, 0, 0, 0, // 0–9：入夜殘餘 → 清晨 → 白天
	0, 0, 0, 0, 1, 1, 2, 2, 3, 3, // 10–19：白天 → 黃昏 → 入夜
	3, 3, 3, 3, 3, 3, 3, 3, 3, 3, // 20–29：深夜
	3, 3, 3, 3, 3, 3, 3, 3, // 30–37
}

// HoursPerDay 是這張表涵蓋的時辰數。
const HoursPerDay = len(lightInsetByHour)

// LightInsetAt 回傳戶外在指定時辰的視野內縮量。
//
// hour 超出範圍時取模 —— 原版直接拿欄位值當索引、不做檢查，
// 這裡寧可回一個合理值也不要越界。
func LightInsetAt(hour int) int {
	h := hour % HoursPerDay
	if h < 0 {
		h += HoursPerDay
	}
	return int(lightInsetByHour[h])
}
